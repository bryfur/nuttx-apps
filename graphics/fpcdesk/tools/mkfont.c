/****************************************************************************
 * apps/graphics/fpcdesk/tools/mkfont.c
 *
 * SPDX-License-Identifier: Apache-2.0
 *
 * Host tool: rasterises TrueType fonts with FreeType into the anti-aliased
 * glyph tables of desk_fonts.c (8-bit coverage, grey-scale hinting), which
 * the desktop uploads into a glyph atlas in the GPU's memory and draws with
 * BLEND (A8 source, tinted).  Characters 32-126, then DESK_EXTRA (below)
 * as codes 127 on.
 *
 *   cc -O2 -o mkfont mkfont.c $(pkg-config --cflags --libs freetype2)
 *   ./mkfont > ../desk_fonts.c        (see mkfont.sh)
 *
 * usage: mkfont NAME:FILE:PIXELS ...
 ****************************************************************************/

#include <ft2build.h>
#include FT_FREETYPE_H

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* Extra characters, codes 127 on (desk_font.h DESK_CH_*) */

static const unsigned long g_extra[] =
{
  0x2022,         /* 127 bullet */
  0x00d7,         /* 128 multiplication sign (close) */
  0x2212,         /* 129 minus (minimise) */
  0x00b0,         /* 130 degree */
  0x2026,         /* 131 ellipsis */
  0x25b8,         /* 132 small right triangle */
  0x00b7,         /* 133 middle dot */
};

#define NEXTRA (sizeof(g_extra) / sizeof(g_extra[0]))
#define NCHARS (95 + NEXTRA)

static unsigned long charcode(int i)
{
  return i < 95 ? (unsigned long)(32 + i) : g_extra[i - 95];
}

int main(int argc, char **argv)
{
  FT_Library lib;
  int f;

  if (FT_Init_FreeType(&lib))
    {
      fprintf(stderr, "mkfont: no FreeType\n");
      return 1;
    }

  printf("/* Generated by tools/mkfont.c: do not edit. */\n\n");
  printf("#include \"desk_font.h\"\n\n");

  for (f = 1; f < argc; f++)
    {
      char spec[512];
      char *name;
      char *file;
      char *px;
      FT_Face face;
      int size;
      int i;
      size_t off = 0;
      int asc;
      int desc;

      snprintf(spec, sizeof(spec), "%s", argv[f]);
      name = strtok(spec, ":");
      file = strtok(NULL, ":");
      px   = strtok(NULL, ":");
      if (name == NULL || file == NULL || px == NULL)
        {
          fprintf(stderr, "mkfont: NAME:FILE:PIXELS, not %s\n", argv[f]);
          return 1;
        }

      size = atoi(px);
      if (FT_New_Face(lib, file, 0, &face) ||
          FT_Set_Pixel_Sizes(face, 0, size))
        {
          fprintf(stderr, "mkfont: cannot load %s\n", file);
          return 1;
        }

      asc  = (int)((face->size->metrics.ascender + 63) >> 6);
      desc = (int)((-face->size->metrics.descender + 63) >> 6);

      /* The coverage bytes of all glyphs, row after row */

      printf("static const uint8_t g_%s_data[] =\n{\n", name);
      for (i = 0; i < (int)NCHARS; i++)
        {
          FT_Bitmap *bm;
          unsigned r;
          unsigned c;

          if (FT_Load_Char(face, charcode(i),
                           FT_LOAD_RENDER | FT_LOAD_TARGET_LIGHT))
            {
              continue;
            }

          bm = &face->glyph->bitmap;
          for (r = 0; r < bm->rows; r++)
            {
              printf("  ");
              for (c = 0; c < bm->width; c++)
                {
                  printf("%u,", bm->buffer[r * bm->pitch + c]);
                }

              printf("\n");
            }
        }

      printf("  0\n};\n\n");

      printf("static const struct desk_glyph_s g_%s_glyphs[%d] =\n{\n",
             name, (int)NCHARS);
      for (i = 0; i < (int)NCHARS; i++)
        {
          FT_GlyphSlot g;

          if (FT_Load_Char(face, charcode(i),
                           FT_LOAD_RENDER | FT_LOAD_TARGET_LIGHT))
            {
              printf("  { 0, 0, 0, 0, 0, 0 },\n");
              continue;
            }

          g = face->glyph;
          printf("  { %u, %u, %d, %d, %d, %zu },   /* U+%04lx */\n",
                 g->bitmap.width, g->bitmap.rows, g->bitmap_left,
                 g->bitmap_top, (int)((g->advance.x + 32) >> 6), off,
                 charcode(i));
          off += (size_t)g->bitmap.width * g->bitmap.rows;
        }

      printf("};\n\n");
      printf("const struct desk_font_s g_desk_font_%s =\n{\n", name);
      printf("  %d, %d, %d, %d, g_%s_glyphs, g_%s_data\n};\n\n",
             size, asc, desc, (int)NCHARS, name, name);
      fprintf(stderr, "mkfont: %s %dpx: %zu bytes, ascent %d descent %d\n",
              name, size, off, asc, desc);
      FT_Done_Face(face);
    }

  FT_Done_FreeType(lib);
  return 0;
}
