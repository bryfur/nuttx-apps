#!/usr/bin/env python3
"""genbig.py OUT.wast: the JIT's cases too big to keep as text: a function
of over 128 KB of code whose br_table's targets are beyond a TBH's reach
(compiled again with its entries to fragments of their own)."""
import sys
N = 16000                      # ~10 bytes of code each
body = "\n".join("      (local.set 1 (i32.add (local.get 1) (i32.const %d)))"
                 % (0x12345 + i * 7919 % 100000) for i in range(N))
total = sum(0x12345 + i * 7919 % 100000 for i in range(N)) & 0xffffffff
if total >= 2**31:
    total -= 2**32
wast = f""";; generated by genbig.py
(module
  (func (export "far-table") (param i32) (result i32)
    (local i32)
    (block $b2
      (block $b1
        (block $b0
          (br_table $b0 $b1 $b2 (local.get 0)))
        (local.set 1 (i32.const 100))
{body}
        (br $b2))
      (local.set 1 (i32.const 200)))
    (local.get 1)))
(assert_return (invoke "far-table" (i32.const 0)) (i32.const {total + 100 if total + 100 < 2**31 else total + 100 - 2**32}))
(assert_return (invoke "far-table" (i32.const 1)) (i32.const 200))
(assert_return (invoke "far-table" (i32.const 2)) (i32.const 0))
(assert_return (invoke "far-table" (i32.const 7)) (i32.const 0))
"""
open(sys.argv[1], "w").write(wast)
