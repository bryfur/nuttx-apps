#!/usr/bin/env python3
"""mkfrozen.py OUT.c DIR [DIR...]: MicroPython's frozen modules (as
source: MICROPY_MODULE_FROZEN_STR) from the .py files of the packages
DIR, for import from ".frozen" in sys.path.  Comment lines are left
blank (line numbers stay right in tracebacks)."""

import os
import sys


def strip(text):
    out = []
    quote = None                     # In a triple-quoted string
    for ln in text.split('\n'):
        s = ln.strip()
        if quote is None and s.startswith('#'):
            out.append('')
            continue
        out.append(ln.rstrip())
        for q in ('"""', "'''"):
            if (quote is None or quote == q) and ln.count(q) % 2:
                quote = None if quote == q else q
    return '\n'.join(out)


def cstr(b):
    parts = []
    for c in b:
        if c == 0x5c:
            parts.append('\\\\')
        elif c == 0x22:
            parts.append('\\"')
        elif c == 0x0a:
            parts.append('\\n"\n"')
        elif 0x20 <= c < 0x7f and c != 0x3f:
            parts.append(chr(c))
        else:
            parts.append('\\%03o' % c)
    return '"' + ''.join(parts) + '"'


def main():
    out, dirs = sys.argv[1], sys.argv[2:]
    files = []
    for d in dirs:
        pkg = os.path.basename(os.path.normpath(d))
        for f in sorted(os.listdir(d)):
            if f.endswith('.py'):
                files.append((pkg + '/' + f, os.path.join(d, f)))
    names = []
    sizes = []
    contents = []
    for name, path in files:
        data = strip(open(path, encoding='utf-8').read()).encode()
        names.append(name)
        sizes.append(len(data))
        contents.append(data)
    c = ['/* Generated by mkfrozen.py from %s: do not edit */' % ' '.join(dirs),
         '#include <stdint.h>',
         'const char mp_frozen_names[] = %s;' %
         ' '.join(cstr(n.encode() + b'\0') for n in names) if names else
         'const char mp_frozen_names[] = "";',
         'const uint32_t mp_frozen_str_sizes[] = {%s0};' %
         ''.join('%d, ' % s for s in sizes),
         'const char mp_frozen_str_content[] =']
    for data in contents:
        c.append(cstr(data + b'\0'))
    c.append(';')
    text = '\n'.join(c) + '\n'
    if not os.path.exists(out) or open(out).read() != text:
        open(out, 'w').write(text)


if __name__ == '__main__':
    main()
